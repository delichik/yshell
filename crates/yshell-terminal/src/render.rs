    fn cell_of(grapheme: &str) -> TerminalCell {
        TerminalCell {
            grapheme: grapheme.to_owned(),
            ..TerminalCell::default()
        }
    }

    fn styled(
        grapheme: &str,
        foreground: TerminalColor,
        background: TerminalColor,
    ) -> TerminalCell {
        let mut cell = cell_of(grapheme);
        cell.foreground = foreground;
        cell.background = background;
        cell
    }

    fn snapshot_of(
        lines: &[Vec<TerminalCell>],
        cursor: Option<(u16, u16)>,
        selection: Option<SelectionRange>,
    ) -> TerminalSnapshot<'_> {
        TerminalSnapshot {
            lines: lines
                .iter()
                .map(|line| Cow::Borrowed(line.as_slice()))
                .collect(),
            cursor,
            selection,
        }
    }

    fn render_lines(
        renderer: &mut TerminalRenderer,
        lines: Vec<Vec<TerminalCell>>,
        cursor: Option<(u16, u16)>,
        selection: Option<SelectionRange>,
    ) -> TerminalFrame {
        renderer.render(&snapshot_of(&lines, cursor, selection))
    }

    fn pixel(frame: &TerminalFrame, x: u32, y: u32) -> [u8; 4] {
        let index = (y * frame.width + x) as usize * 4;
        [
            frame.rgba[index],
            frame.rgba[index + 1],
            frame.rgba[index + 2],
            frame.rgba[index + 3],
        ]
    }

    fn background_rgba() -> [u8; 4] {
        [
            DEFAULT_BACKGROUND.red,
            DEFAULT_BACKGROUND.green,
            DEFAULT_BACKGROUND.blue,
            255,
        ]
    }

    fn is_background(pixel: [u8; 4]) -> bool {
        pixel == background_rgba()
    }

    fn cell_has_content(frame: &TerminalFrame, column: u32, row: u32) -> bool {
        let start_x = column * frame.cell_width;
        let start_y = row * frame.cell_height;
        (start_y..start_y + frame.cell_height).any(|y| {
            (start_x..start_x + frame.cell_width).any(|x| !is_background(pixel(frame, x, y)))
        })
    }

    fn cell_pixels(frame: &TerminalFrame, column: u32, row: u32) -> Vec<[u8; 4]> {
        let start_x = column * frame.cell_width;
        let start_y = row * frame.cell_height;
        let mut pixels = Vec::with_capacity((frame.cell_width * frame.cell_height) as usize);
        for y in start_y..start_y + frame.cell_height {
            for x in start_x..start_x + frame.cell_width {
                pixels.push(pixel(frame, x, y));
            }
        }
        pixels
    }

    /// Coverage of one pixel assuming default-foreground text over the default
    /// background (0.0 = background, 1.0 = fully covered).
    fn pixel_coverage(pixel: [u8; 4]) -> f64 {
        let channels = [
            (f64::from(pixel[0]) - f64::from(DEFAULT_BACKGROUND.red))
                / (f64::from(DEFAULT_FOREGROUND.red) - f64::from(DEFAULT_BACKGROUND.red)),
            (f64::from(pixel[1]) - f64::from(DEFAULT_BACKGROUND.green))
                / (f64::from(DEFAULT_FOREGROUND.green) - f64::from(DEFAULT_BACKGROUND.green)),
            (f64::from(pixel[2]) - f64::from(DEFAULT_BACKGROUND.blue))
                / (f64::from(DEFAULT_FOREGROUND.blue) - f64::from(DEFAULT_BACKGROUND.blue)),
        ];
        (channels.iter().sum::<f64>() / 3.0).clamp(0.0, 1.0)
    }

    /// `(ink pixels, mean coverage of ink pixels, share of ink pixels at >= 90%
    /// coverage)` for a frame drawn with the default foreground/background.
    fn ink_stats(frame: &TerminalFrame) -> (usize, f64, f64) {
        let mut ink = 0usize;
        let mut total = 0.0f64;
        let mut ge90 = 0usize;
        for y in 0..frame.height {
            for x in 0..frame.width {
                if is_background(pixel(frame, x, y)) {
                    continue;
                }
                ink += 1;
                let coverage = pixel_coverage(pixel(frame, x, y));
                total += coverage;
                if coverage >= 0.9 {
                    ge90 += 1;
                }
            }
        }
        let divisor = ink.max(1) as f64;
        (ink, total / divisor, ge90 as f64 / divisor * 100.0)
    }

    /// Ink pixel count per pixel column of one cell.
    fn ink_columns(frame: &TerminalFrame, cell: u32) -> Vec<usize> {
        let left = cell * frame.cell_width;
        (left..left + frame.cell_width)
            .map(|x| {
                (0..frame.cell_height)
                    .filter(|y| !is_background(pixel(frame, x, *y)))
                    .count()
            })
            .collect()
    }

    /// Digits 0-9 (`.` = background) per pixel of a cell span, for test-log
    /// snapshots. `columns` is the number of cells to include.
    fn coverage_grid(frame: &TerminalFrame, row: u32, columns: u32) -> String {
        let start_x = 0;
        let end_x = frame.cell_width * columns;
        let start_y = row * frame.cell_height;
        let mut grid = String::new();
        for y in start_y..start_y + frame.cell_height {
            for x in start_x..end_x {
                let coverage = pixel_coverage(pixel(frame, x, y));
                if coverage <= 0.02 {
                    grid.push('.');
                } else {
                    let digit = ((coverage * 10.0) as usize).min(9);
                    grid.push(char::from(b'0' + digit as u8));
                }
            }
            grid.push('\n');
        }
        grid
    }

    /// Cells for a string, mirroring the grid's wide-character convention
    /// (double-width graphemes are followed by a continuation cell).
    fn wide_text_line(text: &str) -> Vec<TerminalCell> {
        let mut line = Vec::new();
        for character in text.chars() {
            if UnicodeWidthChar::width(character).unwrap_or(1) >= 2 {
                line.extend(wide_cell(character));
            } else {
                line.push(cell_of(&character.to_string()));
            }
        }
        line
    }

