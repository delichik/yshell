    /// `(r, g, b, 255)` for pixel comparisons.
    fn rgba(color: TerminalColor) -> [u8; 4] {
        [color.red, color.green, color.blue, 255]
    }

    /// Whether any pixel of `cell` exactly equals `color` (fully covered pixel).
    fn cell_contains(frame: &TerminalFrame, cell: u32, color: TerminalColor) -> bool {
        let start_x = cell * frame.cell_width;
        (0..frame.cell_height).any(|y| {
            (start_x..start_x + frame.cell_width).any(|x| pixel(frame, x, y) == rgba(color))
        })
    }

