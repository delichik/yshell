    /// Columns used by the W0 evidence frames.
    const EVIDENCE_COLUMNS: usize = 40;

    fn line_from_text(text: &str) -> Vec<TerminalCell> {
        let mut line: Vec<TerminalCell> = text
            .chars()
            .map(|character| cell_of(&character.to_string()))
            .collect();
        line.resize(EVIDENCE_COLUMNS, cell_of(" "));
        line
    }

    /// A wide (two-cell) grapheme followed by its continuation cell.
    fn wide_cell(character: char) -> Vec<TerminalCell> {
        let mut continuation = cell_of(" ");
        continuation.wide_continuation = true;
        vec![cell_of(&character.to_string()), continuation]
    }

    /// Plain frame: no bold/italic cells. Content is frozen: the W0 regression
    /// test compares this frame pixel by pixel against the legacy rasterizer.
    fn plain_evidence_lines() -> Vec<Vec<TerminalCell>> {
        let palette = [
            TerminalColor::RED,
            TerminalColor::GREEN,
            TerminalColor::YELLOW,
            TerminalColor::BLUE,
            TerminalColor::MAGENTA,
            TerminalColor::CYAN,
            TerminalColor::BRIGHT_WHITE,
        ];

        let mut lines = Vec::new();
        lines.push(line_from_text(
            "YShell terminal glyph regression  0123456789",
        ));

        let colored = "ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghij";
        lines.push(
            colored
                .chars()
                .enumerate()
                .map(|(index, character)| {
                    styled(
                        &character.to_string(),
                        palette[index % palette.len()],
                        TerminalColor::BLACK,
                    )
                })
                .collect(),
        );

        let mut underline_row = line_from_text("underlined  \u{2500}\u{2502}\u{250c}\u{2510}\u{2514}\u{2518}\u{251c}\u{2524}\u{252c}\u{2534}\u{253c}");
        for cell in underline_row.iter_mut().take(10) {
            cell.underline = true;
        }
        lines.push(underline_row);

        let mut wide_row = Vec::new();
        for character in ['\u{4f60}', '\u{597d}', '\u{4e16}', '\u{754c}'] {
            wide_row.extend(wide_cell(character));
        }
        wide_row.resize(EVIDENCE_COLUMNS, cell_of(" "));
        lines.push(wide_row);

        lines.push(vec![cell_of(" "); EVIDENCE_COLUMNS]);
        lines.push(line_from_text("!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"));
        lines.push(line_from_text(
            "The quick brown fox jumps over the lazy dog",
        ));
        lines.push(line_from_text("0123456789 0123456789 0123456789 012345"));
        lines
    }

    /// Styled frame: bold / italic / bold-italic cells plus the fallback case
    /// (CJK in a font family without CJK coverage).
    fn styled_evidence_lines() -> Vec<Vec<TerminalCell>> {
        let sample = "Hamburgefonstiv 0123456789";
        let style_row = |bold: bool, italic: bool| {
            sample
                .chars()
                .map(|character| {
                    let mut cell = cell_of(&character.to_string());
                    cell.bold = bold;
                    cell.italic = italic;
                    cell
                })
                .collect::<Vec<_>>()
        };

        let mut lines = vec![
            line_from_text(sample),
            style_row(true, false),
            style_row(false, true),
            style_row(true, true),
        ];

        let palette = [
            TerminalColor::RED,
            TerminalColor::GREEN,
            TerminalColor::YELLOW,
            TerminalColor::BLUE,
            TerminalColor::MAGENTA,
            TerminalColor::CYAN,
        ];
        lines.push(
            "bold colors 0123456789"
                .chars()
                .enumerate()
                .map(|(index, character)| {
                    let mut cell = styled(
                        &character.to_string(),
                        palette[index % palette.len()],
                        TerminalColor::BLACK,
                    );
                    cell.bold = true;
                    cell
                })
                .collect(),
        );

        let mut cjk = Vec::new();
        for (index, character) in ['\u{4f60}', '\u{597d}', '\u{4e16}', '\u{754c}']
            .into_iter()
            .enumerate()
        {
            for mut cell in wide_cell(character) {
                cell.bold = index % 2 == 0;
                cell.italic = index % 2 == 1;
                cjk.push(cell);
            }
        }
        cjk.resize(EVIDENCE_COLUMNS, cell_of(" "));
        lines.push(cjk);

        let mut mixed = Vec::new();
        for (index, character) in "HHHH Wi|".chars().enumerate() {
            let mut cell = cell_of(&character.to_string());
            cell.bold = index % 2 == 0;
            cell.italic = index >= 4;
            mixed.push(cell);
        }
        mixed.resize(EVIDENCE_COLUMNS, cell_of(" "));
        lines.push(mixed);

        lines.push(line_from_text("styled frame end  0123456789"));
        lines
    }

    /// FNV-1a hash, printed alongside the evidence frames so the report can quote
    /// a compact fingerprint of the exact bytes.
    fn fnv1a64(bytes: &[u8]) -> u64 {
        let mut hash = 0xcbf2_9ce4_8422_2325u64;
        for byte in bytes {
            hash ^= u64::from(*byte);
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        hash
    }

    fn evidence_dir() -> PathBuf {
        evidence_path().parent().expect("dist dir").to_path_buf()
    }

    fn write_frame_evidence(name: &str, renderer: &TerminalRenderer, frame: &TerminalFrame) {
        let dir = evidence_dir();
        std::fs::create_dir_all(&dir).expect("create dist dir");
        let rgba_path = dir.join(format!("{name}.rgba"));
        let png_path = dir.join(format!("{name}.png"));
        std::fs::write(&rgba_path, &frame.rgba).expect("write evidence rgba");
        std::fs::write(
            &png_path,
            png::encode_rgba(frame.width, frame.height, &frame.rgba),
        )
        .expect("write evidence png");
        let (cell_width, cell_height) = renderer.cell_size();
        let meta = format!(
            "name={name}\nwidth={}\nheight={}\ncell_width={cell_width}\ncell_height={cell_height}\nlogical_font_size={}\nfnv1a64={:016x}\n",
            frame.width,
            frame.height,
            renderer.font_size(),
            fnv1a64(&frame.rgba),
        );
        std::fs::write(dir.join(format!("{name}.meta.txt")), meta).expect("write evidence meta");
        eprintln!(
            "w0-evidence {name}: {}x{} cells {cell_width}x{cell_height} fnv1a64={:016x}",
            frame.width,
            frame.height,
            fnv1a64(&frame.rgba),
        );
    }

