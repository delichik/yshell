    #[test]
    fn user_fallback_files_are_tried_before_the_bundled_cjk_subset() {
        // The GB2312 subset has no '€' (U+20AC) while DejaVu Sans Mono does.
        let cjk_file = asset_path("NotoSansMonoCJKsc-GB2312-Subset.otf");
        let dejavu_file = asset_path("DejaVuSansMono.ttf");
        let selection =
            FontSelection::with_primary_file(&cjk_file).with_fallback_file(&dejavu_file);
        let (set, rejected) = TerminalFontSet::from_selection(&selection);
        assert!(rejected.is_empty());
        let chain: Vec<&str> = set.regular().faces().map(FontFace::name).collect();
        assert_eq!(chain.len(), 3, "primary + user fallback + bundled CJK");
        assert_eq!(chain[1], dejavu_file.display().to_string());
        assert!(
            chain[2].contains("CJK"),
            "the bundled CJK subset must stay the last resort, got {chain:?}"
        );
        let resolved = set
            .resolve('\u{20ac}', GlyphStyle::default())
            .expect("the user fallback must cover '€'");
        assert_eq!(resolved.face.name(), dejavu_file.display().to_string());

        // Pixel evidence: with the fallback the euro sign paints a real glyph;
        // without it the primary face only has the hollow `.notdef` box.
        let mut with_fallback = TerminalRenderer::new();
        let rejected =
            with_fallback.apply_appearance(TerminalPalette::default(), selection.clone());
        assert!(rejected.is_empty());
        let painted = render_lines(
            &mut with_fallback,
            vec![vec![cell_of("\u{20ac}")]],
            None,
            None,
        );

        let mut without_fallback = TerminalRenderer::new();
        let rejected = without_fallback.apply_appearance(
            TerminalPalette::default(),
            FontSelection::with_primary_file(&cjk_file),
        );
        assert!(rejected.is_empty());
        let notdef = render_lines(
            &mut without_fallback,
            vec![vec![cell_of("\u{20ac}")]],
            None,
            None,
        );

        assert!(cell_has_content(&painted, 0, 0));
        assert_ne!(
            painted.rgba, notdef.rgba,
            "the user fallback face must change the rasterized glyph"
        );
    }

