    #[test]
    fn palette_change_keeps_the_glyph_cache_and_font_change_drops_it() {
        let lines = || vec![vec![cell_of("H"), cell_of("i")]];
        let mut renderer = TerminalRenderer::new();
        let _ = render_lines(&mut renderer, lines(), None, None);
        let cached = renderer.glyph_cache_len();
        assert!(cached >= 2, "expected cached glyphs, got {cached}");

        // Palette changes are paint-time only: the cached bitmaps stay valid.
        let dracula = crate::palette::color_scheme("dracula")
            .expect("dracula is a built-in scheme")
            .palette;
        let rejected = renderer.apply_appearance(dracula, FontSelection::default());
        assert!(rejected.is_empty());
        assert_eq!(renderer.glyph_cache_len(), cached);

        // A different font rebuilds the chains and drops every cached glyph.
        let bold_file = asset_path("DejaVuSansMono-Bold.ttf");
        let rejected = renderer.apply_appearance(
            TerminalPalette::default(),
            FontSelection::with_primary_file(&bold_file),
        );
        assert!(rejected.is_empty());
        assert_eq!(renderer.glyph_cache_len(), 0);
        let _ = render_lines(&mut renderer, lines(), None, None);
        assert_eq!(renderer.glyph_cache_len(), cached);
    }

