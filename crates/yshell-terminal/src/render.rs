    #[test]
    fn scale_factor_scales_the_physical_cell_size() {
        let base = TerminalRenderer::new();
        let (base_width, base_height) = base.cell_size();
        assert_eq!(base.scale_factor(), 1.0);
        assert_eq!(base.physical_font_size(), DEFAULT_FONT_SIZE);

        let mut scaled = TerminalRenderer::with_scale_factor(DEFAULT_FONT_SIZE, 2.0);
        assert_eq!(scaled.scale_factor(), 2.0);
        assert_eq!(scaled.physical_font_size(), 32.0);
        // 32px advance rounds to 19px (not 2x10): physical cell metrics are
        // re-measured at the physical size, so x-scaling is not exactly 2x.
        let (scaled_width, scaled_height) = scaled.cell_size();
        assert_eq!((scaled_width, scaled_height), (19, 38));

        let quarter = TerminalRenderer::with_scale_factor(DEFAULT_FONT_SIZE, 1.25);
        assert_eq!(quarter.physical_font_size(), 20.0);
        assert_eq!(quarter.cell_size(), (12, 24));
        assert_eq!(scaled_height, 38);

        let frame = render_lines(&mut scaled, vec![vec![cell_of("A"); 2]], None, None);
        assert_eq!(frame.cell_width, scaled_width);
        assert_eq!(frame.cell_height, scaled_height);
        assert_eq!(frame.width, scaled_width * 2);
        assert_eq!(frame.height, scaled_height);

        // Re-scaling re-measures the cells and drops the cached glyphs.
        scaled.set_scale_factor(1.0);
        assert_eq!(scaled.cell_size(), (base_width, base_height));
        let unscaled = render_lines(&mut scaled, vec![vec![cell_of("A"); 2]], None, None);
        assert_eq!(unscaled.cell_width, base_width);

        // Invalid scale factors fall back to 1.0.
        let fallback = TerminalRenderer::with_scale_factor(DEFAULT_FONT_SIZE, f32::NAN);
        assert_eq!(fallback.scale_factor(), 1.0);
        let fallback = TerminalRenderer::with_scale_factor(DEFAULT_FONT_SIZE, 0.0);
        assert_eq!(fallback.scale_factor(), 1.0);
    }

