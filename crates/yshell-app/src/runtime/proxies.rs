    /// Validates the form and creates/updates the managed profile.
    pub fn save_proxy_editor(&mut self) -> AppProjection {
        match self.persist_proxy_editor() {
            Ok((id, created)) => {
                self.proxies_selected_id = Some(id.clone());
                self.proxies_editor_id = Some(id);
                self.proxies_editor_password.clear();
                self.proxies_remove_blocked = false;
                let status_text = if created {
                    "Saved the new proxy profile.".to_owned()
                } else {
                    "Saved proxy profile changes; all referencing sessions use them.".to_owned()
                };
                let kind = if created {
                    "proxies-saved-new"
                } else {
                    "proxies-saved-changes"
                };
                self.set_proxies_status_kind(
                    kind,
                    status_text.clone(),
                    String::new(),
                    String::new(),
                );
                self.set_status_kind(kind, status_text, String::new(), String::new());
            }
            Err(error) => {
                self.set_proxies_status_kind(
                    "proxies-save-failed",
                    format!("Cannot save proxy profile: {error}"),
                    error.to_string(),
                    String::new(),
                );
            }
        }
        self.projection()
    }

    fn persist_proxy_editor(&mut self) -> AppResult<(String, bool)> {
        let name = self.proxies_editor_name.trim().to_owned();
        if name.is_empty() {
            return Err(AppError::new("a proxy name must not be empty"));
        }
        let host = self.proxies_editor_host.trim().to_owned();
        if host.is_empty() {
            return Err(AppError::new("a proxy host must not be empty"));
        }
        let port = parse_port_field(
            &self.proxies_editor_port_text,
            "proxy port must be a valid integer between 1 and 65535",
        )?;
        let created = self.proxies_editor_id.is_none();
        let id = match &self.proxies_editor_id {
            Some(id) => {
                if !self.config_document.proxy_profiles.contains_key(id) {
                    return Err(AppError::new(format!(
                        "proxy profile `{id}` no longer exists"
                    )));
                }
                id.clone()
            }
            None => self.allocate_proxy_id(),
        };
        let previous = self.config_document.proxy_profiles.get(&id).cloned();
        let username = {
            let trimmed = self.proxies_editor_username.trim();
            if trimmed.is_empty() {
                None
            } else {
                Some(trimmed.to_owned())
            }
        };
        let secret_ref = proxy_password_secret_ref(&id);
        let password_secret_key = if matches!(
            self.proxies_editor_protocol,
            ProxyProtocol::Socks4 | ProxyProtocol::Socks4a
        ) {
            // SOCKS4/SOCKS4a have no password field: drop a stale stored secret.
            if let Some(previous_secret) = previous
                .as_ref()
                .and_then(|profile| profile.password_secret_key.as_deref())
            {
                let _ = self.delete_secret_value(previous_secret);
            }
            None
        } else if !self.proxies_editor_password.is_empty() {
            self.store_secret_value(&secret_ref, &self.proxies_editor_password)?;
            Some(secret_ref.clone())
        } else if previous
            .as_ref()
            .is_some_and(|profile| profile.password_secret_key.is_some())
        {
            previous
                .as_ref()
                .and_then(|profile| profile.password_secret_key.clone())
        } else {
            None
        };
        let profile = ProxyProfile {
            id: id.clone(),
            name,
            protocol: self.proxies_editor_protocol,
            host,
            port,
            username,
            resolve_dns_by_proxy: self.proxies_editor_dns_by_proxy,
            password_secret_key,
        };
        self.config_document
            .proxy_profiles
            .insert(id.clone(), profile);
        if let Err(error) = self.save_proxy_config() {
            match previous {
                Some(previous) => {
                    self.config_document.proxy_profiles.insert(id.clone(), previous);
                }
                None => {
                    self.config_document.proxy_profiles.remove(&id);
                }
            }
            return Err(error);
        }
        Ok((id, created))
    }

    // --- deletion (D8) ----------------------------------------------------

    pub fn request_proxy_remove(&mut self) -> AppProjection {
        let Some(profile) = self.selected_proxy_profile() else {
            self.set_proxies_status_kind(
                "proxies-remove-requires-selection",
                "Select a proxy profile to delete.".to_owned(),
                String::new(),
                String::new(),
            );
            return self.projection();
        };
        let used_by = self.proxy_used_by();
        let references = used_by.get(&profile.id).cloned().unwrap_or_default();
        if references.is_empty() {
            self.proxies_remove_blocked = false;
            self.proxies_referencing_text.clear();
            self.proxies_remove_confirm_visible = true;
            let status_text = format!("Confirm deleting proxy profile `{}`.", profile.name);
            self.set_proxies_status_kind(
                "proxies-remove-confirm",
                status_text.clone(),
                profile.name.clone(),
                String::new(),
            );
            self.set_status_kind(
                "proxies-remove-confirm",
                status_text,
                profile.name,
                String::new(),
            );
        } else {
            self.proxies_remove_confirm_visible = false;
            self.proxies_remove_blocked = true;
            let referencing = references.join(", ");
            self.proxies_referencing_text = referencing.clone();
            let status_text = format!(
                "Cannot delete `{}`: it is used by {} saved session(s): {}. Set those sessions to No Proxy first.",
                profile.name,
                references.len(),
                referencing
            );
            self.set_proxies_status_kind(
                "proxies-remove-blocked",
                status_text.clone(),
                profile.name.clone(),
                referencing.clone(),
            );
            self.set_status_kind(
                "proxies-remove-blocked",
                status_text,
                profile.name,
                referencing,
            );
        }
        self.projection()
    }

    pub fn cancel_proxy_remove(&mut self) -> AppProjection {
        self.proxies_remove_confirm_visible = false;
        self.projection()
    }

    /// Hides the D8 "deletion blocked" explanation without changing anything.
    pub fn dismiss_proxy_remove_warning(&mut self) -> AppProjection {
        self.proxies_remove_blocked = false;
        self.proxies_referencing_text.clear();
        self.projection()
    }

    pub fn confirm_proxy_remove(&mut self) -> AppProjection {
        self.proxies_remove_confirm_visible = false;
        let Some(profile) = self.selected_proxy_profile() else {
            return self.projection();
        };
        match self.remove_proxy_profile(&profile.id) {
            Ok(removed) => {
                if self.proxies_editor_id.as_deref() == Some(removed.id.as_str()) {
                    self.proxies_editor_id = None;
                    self.start_new_proxy();
                }
                if self.editor.proxy_profile_id.as_deref() == Some(removed.id.as_str()) {
                    self.editor.proxy_mode = EditorProxyMode::None;
                    self.editor.proxy_profile_id = None;
                }
                self.ensure_proxy_selection();
                if self.proxies_selected_id.is_some() {
                    self.begin_edit_proxy();
                }
                let status_text = format!("Deleted proxy profile `{}`.", removed.name);
                self.set_proxies_status_kind(
                    "proxies-deleted",
                    status_text.clone(),
                    removed.name.clone(),
                    String::new(),
                );
                self.set_status_kind(
                    "proxies-deleted",
                    status_text,
                    removed.name,
                    String::new(),
                );
            }
            Err(error) => {
                self.set_proxies_status_kind(
                    "proxies-delete-failed",
                    format!("Delete failed: {error}"),
                    error.to_string(),
                    String::new(),
                );
            }
        }
        self.projection()
    }

    /// D8 explicit alternative: clear the profile from every referencing session.
    pub fn set_referencing_sessions_to_no_proxy(&mut self) -> AppProjection {
        let Some(profile) = self.selected_proxy_profile() else {
            return self.projection();
        };
        let cleared = clear_proxy_from_sessions(
            &mut self.config_document.folders,
            profile.id.as_str(),
        );
        if cleared == 0 {
            self.set_proxies_status_kind(
                "proxies-no-references",
                format!(
                    "No saved session references `{}` anymore.",
                    profile.name
                ),
                profile.name,
                String::new(),
            );
            self.proxies_remove_blocked = false;
            return self.projection();
        }
        match self.save_proxy_config() {
            Ok(()) => {
                self.proxies_remove_blocked = false;
                self.proxies_referencing_text.clear();
                let status_text = format!(
                    "Cleared proxy `{}` from {cleared} saved session(s); they now use No Proxy.",
                    profile.name
                );
                self.set_proxies_status_kind(
                    "proxies-cleared-from-sessions",
                    status_text.clone(),
                    profile.name.clone(),
                    cleared.to_string(),
                );
                self.set_status_kind(
                    "proxies-cleared-from-sessions",
                    status_text,
                    profile.name,
                    cleared.to_string(),
                );
            }
            Err(error) => {
                self.set_proxies_status_kind(
                    "proxies-clear-from-sessions-failed",
                    format!("Cannot update saved sessions: {error}"),
                    error.to_string(),
                    String::new(),
                );
            }
        }
        self.projection()
    }

    fn remove_proxy_profile(&mut self, proxy_id: &str) -> AppResult<ProxyProfile> {
        let profile = self
            .config_document
            .proxy_profiles
            .remove(proxy_id)
            .ok_or_else(|| AppError::new(format!("proxy profile `{proxy_id}` was not found")))?;
        if let Some(secret_key) = profile.password_secret_key.as_deref() {
            let _ = self.delete_secret_value(secret_key);
        }
        if let Err(error) = self.save_proxy_config() {
            self.config_document
                .proxy_profiles
                .insert(proxy_id.to_owned(), profile.clone());
            return Err(error);
        }
        Ok(profile)
    }

