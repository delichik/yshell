//! NET-1: managed proxy profiles.
//!
//! The Proxy Manager page stores one [`ProxyProfile`] per entry in
//! `config.toml`; passwords stay in the secret store and are only referenced by
//! `password_secret_key`. Sessions reference a profile through
//! `proxy_profile_id`, so editing a profile immediately affects every session
//! that uses it and saving a session never duplicates the profile.
//!
//! Per-session `<session_id>-proxy` profiles written by older builds stay
//! loadable. They are presented as *legacy* in the session editor and are
//! removed when the user migrates the session to a managed profile and no other
//! session still references them (see [`AppRuntime::cleanup_legacy_proxy`]).

