/// Upper bound for the Proxy Manager "Test" action (TCP connect + handshake).
pub(crate) const PROXY_TEST_TIMEOUT: Duration = Duration::from_secs(4);

/// Secret-store reference of a managed proxy password.
#[must_use]
pub(crate) fn proxy_password_secret_ref(proxy_id: &str) -> String {
    format!("local://yshell/proxies/{proxy_id}/password")
}

/// Legacy per-session proxy id generated by pre-NET-1 builds.
fn legacy_proxy_profile_id(session_id: &str) -> String {
    format!("{session_id}-proxy")
}

/// Whether `proxy_id` is the legacy per-session profile of `session_id`.
#[must_use]
pub(crate) fn is_legacy_proxy_profile_id(session_id: &str, proxy_id: &str) -> bool {
    proxy_id == legacy_proxy_profile_id(session_id)
}

/// Display name of a proxy protocol (technical labels are not translated).
#[must_use]
pub(crate) fn proxy_protocol_display(protocol: ProxyProtocol) -> &'static str {
    match protocol {
        ProxyProtocol::Socks4 => "SOCKS4",
        ProxyProtocol::Socks4a => "SOCKS4a",
        ProxyProtocol::Socks5 => "SOCKS5",
        ProxyProtocol::HttpConnect => "HTTP CONNECT",
    }
}

/// Protocol index used by the Proxy Manager combo box.
#[must_use]
pub(crate) const fn proxy_protocol_index(protocol: ProxyProtocol) -> i32 {
    match protocol {
        ProxyProtocol::Socks4 => 0,
        ProxyProtocol::Socks4a => 1,
        ProxyProtocol::Socks5 => 2,
        ProxyProtocol::HttpConnect => 3,
    }
}

/// Protocol for a Proxy Manager combo box index (out-of-range → SOCKS5).
#[must_use]
pub(crate) const fn proxy_protocol_at(index: i32) -> ProxyProtocol {
    match index {
        0 => ProxyProtocol::Socks4,
        1 => ProxyProtocol::Socks4a,
        3 => ProxyProtocol::HttpConnect,
        _ => ProxyProtocol::Socks5,
    }
}

